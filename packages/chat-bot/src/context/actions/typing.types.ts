/** Управляет статусом «печатает» во время выполнения `withTyping()`. */
export interface ChatTypingControl {
  /** Запускает или возобновляет отправку статуса, когда предыдущий запрос завершён. */
  start(): void;
  /** Приостанавливает отправку статуса. */
  stop(): void;
}

/** Настройки статуса «печатает». */
export interface ChatTypingOptions {
  /** Задержка после завершения запроса до следующего обновления, в миллисекундах. По умолчанию 4000. */
  interval?: number;
  /** Ждать первого вызова `start()` перед отправкой статуса. */
  startPaused?: boolean;
}
