/**
 * Ошибка плагина шифрования.
 *
 * Возникает при некорректной конфигурации либо запросе, который нельзя безопасно
 * преобразовать до отправки: неизвестном шифре, неверном диапазоне, пересечении
 * семантической разметки, превышении длины или нарушении контракта пользовательского
 * алгоритма.
 *
 * Сетевые и серверные ошибки продолжают использовать обычные ошибки `itd-api`.
 */
export class CryptError extends Error {
  constructor(message: string, options?: ErrorOptions) {
    super(message, options);
    this.name = 'CryptError';
  }
}
