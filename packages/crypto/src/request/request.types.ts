import type { CipherRef } from '../ciphers/cipher.types.js';

/**
 * Участок исходного текста, который нужно зашифровать.
 *
 * Смещение и длина измеряются в кодовых единицах UTF-16 — так же, как `String#slice`
 * и обычные `Span`. Диапазон должен быть непустым, находиться внутри поля и не
 * пересекаться с другим криптографическим диапазоном того же поля.
 *
 * @example Зашифровать слово «секрет» в строке «видно секрет видно»
 * ```ts
 * const range: CryptoRange = {
 *   field: 'content',
 *   cipher: CipherName.Invisible,
 *   offset: 6,
 *   length: 6,
 * };
 * ```
 */
export interface CryptoRange {
  /** Имя поля. Обязательно, если у операции несколько доступных текстовых полей. */
  field?: string | undefined;
  /** Имя или числовой идентификатор шифра для этого участка. */
  cipher: CipherRef;
  /** Начало участка в кодовых единицах UTF-16. */
  offset: number;
  /** Длина участка в кодовых единицах UTF-16; должна быть больше нуля. */
  length: number;
}

/**
 * Настройки шифрования для одного низкоуровневого вызова.
 *
 * Доступны два взаимоисключающих режима:
 *
 * - `encrypt` шифрует указанным алгоритмом каждое переданное непустое текстовое поле;
 * - `spans` шифрует только перечисленные диапазоны, причём каждый выбирает свой алгоритм.
 *
 * Пустой массив `spans` и одновременная передача `encrypt` со `spans` являются ошибкой.
 *
 * @example
 * ```ts
 * await itd.posts.comment('post-id', 'видно секрет видно', {
 *   extensions: {
 *     crypto: {
 *       spans: [{ cipher: 'invisible', offset: 6, length: 6 }],
 *     },
 *   },
 * });
 * ```
 */
export interface RawCryptoOptions {
  /** Шифр для всех переданных непустых текстовых полей. */
  encrypt?: CipherRef | undefined;
  /** Независимые зашифрованные диапазоны. */
  spans?: readonly CryptoRange[] | undefined;
}
