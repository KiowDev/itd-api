import type { Span } from 'itd-api';

/**
 * Имена встроенных шифров.
 *
 * @example
 * ```ts
 * await itd.posts.create(
 *   { content: 'секрет' },
 *   { extensions: { crypto: { encrypt: CipherName.Invisible } } },
 * );
 *
 * // Обычная строка тоже допустима.
 * await itd.posts.create(
 *   { content: 'секрет' },
 *   { extensions: { crypto: { encrypt: 'invisible' } } },
 * );
 * ```
 */
export const CipherName = Object.freeze({
  /** Видимый шифротекст из букв `ж`, `ъ`, `Ж` и `Ъ`; шифрует только поле целиком. */
  BeeCrypt: 'beecrypt',
  /** Невидимая нагрузка в общем контейнере; поддерживает отдельные фрагменты. */
  Invisible: 'invisible',
} as const);
export type CipherName = (typeof CipherName)[keyof typeof CipherName];

/**
 * Ссылка на подключённый шифр: его имя либо стабильный числовой идентификатор.
 *
 * Имя удобнее в прикладном коде, а идентификатор позволяет хранить выбор шифра в данных
 * приложения без дополнительного преобразования.
 */
export type CipherRef = string | number;

/**
 * Алгоритм преобразования текста.
 *
 * Шифр не знает об операциях API, полях моделей и координатах разметки. Для фрагментного
 * режима он получает только точный текст участка, а возвращённая нагрузка помещается
 * плагином в общий контейнер с границами и {@link id}. Шифр целого поля получает всё поле.
 *
 * `decode()` обязан строго отличать свой формат от постороннего текста и возвращать
 * `null`, если вход ему не принадлежит. Выброшенная ошибка или значение другого типа
 * считаются нарушением контракта.
 *
 * @example Фрагментный пользовательский шифр
 * ```ts
 * const brackets: Cipher = {
 *   name: 'brackets',
 *   id: 5,
 *   supportsFragments: true,
 *   encode: (text) => `[${text}]`,
 *   decode: (encoded) =>
 *     encoded.startsWith('[') && encoded.endsWith(']')
 *       ? encoded.slice(1, -1)
 *       : null,
 * };
 * ```
 */
export interface Cipher {
  /** Уникальное непустое имя, используемое в настройках и {@link CryptoSpan.cipher}. */
  name: string;
  /**
   * Уникальный неотрицательный безопасный целочисленный идентификатор.
   *
   * Он записывается в транспортный контейнер и {@link CryptoSpan.cipherId}. После
   * публикации формата идентификатор нельзя назначать другому алгоритму.
   * Пользовательским алгоритмам следует назначать идентификаторы начиная с `3`.
   */
  id: number;
  /**
   * Требует ли алгоритм сохранности символов `U+206A`…`U+206F`.
   *
   * Такой шифр нельзя использовать для `displayName` и `bio`: серверная сохранность
   * невидимого алфавита для этих полей не подтверждена.
   */
  requiresInvisibleAlphabet?: boolean | undefined;
  /**
   * Можно ли использовать результат `encode()` как нагрузку внутри общего контейнера.
   *
   * При `true` шифр поддерживает отдельные фрагменты. Отсутствующее значение означает,
   * что алгоритм применяется только к полю целиком.
   */
  supportsFragments?: boolean | undefined;
  /**
   * Кодирует переданный текст. Метод отсутствует у алгоритма, доступного только для чтения.
   *
   * Результат фрагментного шифра не должен содержать маркеры начала или конца контейнера.
   */
  encode?(text: string): string;
  /**
   * Декодирует точную нагрузку либо целое поле.
   *
   * @returns исходный текст или `null`, если вход не относится к этому шифру
   */
  decode(text: string): string | null;
}

/**
 * Участок исходного текста, который нужно зашифровать.
 *
 * Смещение и длина измеряются в кодовых единицах UTF-16 — так же, как `String#slice`
 * и обычные `Span`. Диапазон должен быть непустым, находиться внутри поля и не
 * пересекаться с другим криптографическим диапазоном того же поля.
 *
 * @example Зашифровать слово «секрет» в строке «видно секрет видно»
 * ```ts
 * const range: CryptoRange = {
 *   field: 'content',
 *   cipher: CipherName.Invisible,
 *   offset: 6,
 *   length: 6,
 * };
 * ```
 */
export interface CryptoRange {
  /** Имя поля. Обязательно, если у операции несколько доступных текстовых полей. */
  field?: string | undefined;
  /** Имя или числовой идентификатор шифра для этого участка. */
  cipher: CipherRef;
  /** Начало участка в кодовых единицах UTF-16. */
  offset: number;
  /** Длина участка в кодовых единицах UTF-16; должна быть больше нуля. */
  length: number;
}

/**
 * Настройки шифрования для одного низкоуровневого вызова.
 *
 * Доступны два взаимоисключающих режима:
 *
 * - `encrypt` шифрует указанным алгоритмом каждое переданное непустое текстовое поле;
 * - `spans` шифрует только перечисленные диапазоны, причём каждый выбирает свой алгоритм.
 *
 * Пустой массив `spans` и одновременная передача `encrypt` со `spans` являются ошибкой.
 *
 * @example
 * ```ts
 * await itd.posts.comment('post-id', 'видно секрет видно', {
 *   extensions: {
 *     crypto: {
 *       spans: [{ cipher: 'invisible', offset: 6, length: 6 }],
 *     },
 *   },
 * });
 * ```
 */
export interface RawCryptoOptions {
  /** Шифр для всех переданных непустых текстовых полей. */
  encrypt?: CipherRef | undefined;
  /** Независимые зашифрованные диапазоны. */
  spans?: readonly CryptoRange[] | undefined;
}

/**
 * Локальная разметка успешно расшифрованного участка.
 *
 * Она существует только внутри {@link DecodedField.spans} и никогда не отправляется
 * серверу. Обычная и криптографическая разметка могут пересекаться: например, секретный
 * участок может одновременно быть жирным.
 */
export interface CryptoSpan {
  /** Отличает криптографическую разметку от обычных серверных типов. */
  type: 'crypto';
  /** Читаемое имя алгоритма. */
  cipher: string;
  /** Стабильный идентификатор алгоритма из транспортного контейнера. */
  cipherId: number;
  /** Начало участка в строке {@link DecodedField.text}. */
  offset: number;
  /** Длина расшифрованного участка в кодовых единицах UTF-16. */
  length: number;
}

/**
 * Готовое расшифрованное представление одного исходного поля.
 *
 * Исходное поле объекта сохраняет ответ сервера. Для отображения текста вместе с
 * открытыми и расшифрованными участками нужно использовать свойства `text` и `spans`
 * из этого объекта.
 *
 * @example
 * ```ts
 * const post = await itd.posts.get(postId);
 * const content = post.decoded?.content;
 * if (content) renderText(content.text, content.spans);
 * ```
 */
export interface DecodedField {
  /** Смешанный текст: открытые части и успешно расшифрованные участки. */
  text: string;
  /** Серверная и криптографическая разметка в координатах свойства `text`. */
  spans: Array<Span | CryptoSpan>;
}

/** Расшифрованные представления, сгруппированные по исходному имени поля. */
export type DecodedFields = Record<string, DecodedField | undefined>;

/**
 * Дополнение моделей `itd-api`, у которых найден хотя бы один зашифрованный участок.
 *
 * Свойство не создаётся, если ни одно поле объекта расшифровать не удалось.
 */
export interface CryptoDecodedObject {
  /** Готовые представления успешно расшифрованных полей. */
  decoded?: DecodedFields | undefined;
}
