/**
 * Ссылка на подключённый шифр: его имя либо стабильный числовой идентификатор.
 *
 * Имя удобнее в прикладном коде, а идентификатор позволяет хранить выбор шифра в данных
 * приложения без дополнительного преобразования.
 */
export type CipherRef = string | number;

/**
 * Алгоритм преобразования текста.
 *
 * Шифр не знает об операциях API, полях моделей и координатах разметки. Для фрагментного
 * режима он получает только точный текст участка, а возвращённая нагрузка помещается
 * плагином в общий контейнер с границами и {@link id}. Для whole-field режима любой шифр
 * получает всё поле, а результат отправляется без контейнера.
 *
 * `decode()` обязан строго отличать свой формат от постороннего текста и возвращать
 * `null`, если вход ему не принадлежит. Выброшенная ошибка или значение другого типа
 * считаются нарушением контракта.
 *
 * @example Фрагментный пользовательский шифр
 * ```ts
 * const brackets: Cipher = {
 *   name: 'brackets',
 *   id: 5,
 *   supportsFragments: true,
 *   encode: (text) => `[${text}]`,
 *   decode: (encoded) =>
 *     encoded.startsWith('[') && encoded.endsWith(']')
 *       ? encoded.slice(1, -1)
 *       : null,
 * };
 * ```
 */
export interface Cipher {
  /** Уникальное непустое имя, используемое в настройках и {@link CryptoSpan.cipher}. */
  name: string;
  /**
   * Уникальный неотрицательный безопасный целочисленный идентификатор.
   *
   * Он записывается в транспортный контейнер фрагмента и {@link CryptoSpan.cipherId}.
   * После публикации формата идентификатор нельзя назначать другому алгоритму.
   * Пользовательским алгоритмам следует назначать идентификаторы начиная с `2`.
   */
  id: number;
  /**
   * Требует ли алгоритм сохранности символов `U+206A`…`U+206F`.
   *
   * Такой шифр нельзя использовать для `displayName` и `bio`: серверная сохранность
   * невидимого алфавита для этих полей не подтверждена.
   */
  requiresInvisibleAlphabet?: boolean | undefined;
  /**
   * Можно ли использовать результат `encode()` как нагрузку внутри общего контейнера.
   *
   * При `true` шифр поддерживает отдельные фрагменты. Отсутствующее значение означает,
   * что алгоритм применяется только к полю целиком.
   */
  supportsFragments?: boolean | undefined;
  /**
   * Кодирует переданный текст. Метод отсутствует у алгоритма, доступного только для чтения.
   *
   * Результат фрагментного шифра не должен содержать маркеры начала или конца контейнера.
   */
  encode?(text: string): string;
  /**
   * Декодирует точную нагрузку либо целое поле.
   *
   * @returns исходный текст или `null`, если вход не относится к этому шифру
   */
  decode(text: string): string | null;
}
